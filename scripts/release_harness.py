#!/usr/bin/env python3
"""Isolated source and release artifact checks for VoiceTyping."""

from __future__ import annotations

import argparse
import ast
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
PACKAGE_MODULES = (
    "__main__",
    "app",
    "audio_routing",
    "auto_paste",
    "core",
    "desktop_environment",
    "desktop_integration",
    "live_transcription",
    "recording_recovery",
    "setup_shortcut",
    "shortcuts",
    "voice_overlay",
    "voice_visual",
    "voicetyping_toggle",
    "xdg_portal",
)
# voice_overlay imports the distro-provided Cairo binding. Its presence is
# checked in the wheel and Linux artifacts, while the clean PyPI-only venv
# imports every module that does not require an OS desktop binding.
CLEAN_VENV_IMPORT_MODULES = tuple(
    module for module in PACKAGE_MODULES if module != "voice_overlay"
)
REQUIREMENTS_HEADER = (
    "# This file was autogenerated by uv via the following command:\n",
    "#    uv export --locked --no-emit-project --output-file requirements.txt\n",
)


def run(
    command: list[str],
    *,
    cwd: Path = ROOT,
    env: dict[str, str] | None = None,
    quiet: bool = False,
) -> None:
    print("+", " ".join(str(part) for part in command), flush=True)
    subprocess.run(
        command,
        cwd=cwd,
        env=env,
        check=True,
        stdout=subprocess.DEVNULL if quiet else None,
    )


def isolated_environment(root: Path) -> dict[str, str]:
    """Return an environment that cannot read the user's app state or API key."""
    home = root / "home"
    runtime = root / "runtime"
    recovery = root / "recovery"
    for directory in (home, runtime, recovery):
        directory.mkdir(parents=True, mode=0o700, exist_ok=True)
        directory.chmod(0o700)

    environment = os.environ.copy()
    for variable in (
        "GEMINI_API_KEY",
        "GOOGLE_API_KEY",
        "PYTHONHOME",
        "PYTHONPATH",
        "VIRTUAL_ENV",
    ):
        environment.pop(variable, None)
    environment.update(
        {
            "HOME": str(home),
            "XDG_CONFIG_HOME": str(home / ".config"),
            "XDG_DATA_HOME": str(home / ".local/share"),
            "XDG_STATE_HOME": str(home / ".local/state"),
            "XDG_RUNTIME_DIR": str(runtime),
            "XDG_CURRENT_DESKTOP": "VoiceTyping-Test",
            "VOICETYPING_RECOVERY_DIR": str(recovery),
            "PYTHONNOUSERSITE": "1",
        }
    )
    return environment


def require_file(path: Path, description: str) -> Path:
    if not path.is_file():
        raise FileNotFoundError(f"{description} not found: {path}")
    return path.resolve()


def select_wheel(value: str | None) -> Path:
    if value:
        return require_file(Path(value), "Wheel")
    wheels = sorted(DIST.glob("voicetyping-*.whl"))
    if len(wheels) != 1:
        raise RuntimeError(
            f"Expected one VoiceTyping wheel in {DIST}, found {len(wheels)}; pass --wheel."
        )
    return wheels[0].resolve()


def source_checks(_args: argparse.Namespace) -> None:
    with tempfile.TemporaryDirectory(prefix="voicetyping-source-") as temporary:
        root = Path(temporary)
        exported = root / "requirements.txt"
        environment = isolated_environment(root / "environment")
        run(["uv", "lock", "--check"], env=environment)
        run(
            [
                "uv",
                "export",
                "--locked",
                "--no-emit-project",
                "--output-file",
                str(exported),
            ],
            env=environment,
            quiet=True,
        )
        checked_in = (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines(
            keepends=True
        )
        generated = exported.read_text(encoding="utf-8").splitlines(keepends=True)
        if checked_in[:2] != list(REQUIREMENTS_HEADER):
            raise RuntimeError("requirements.txt has a non-canonical uv export header.")
        if (
            generated[:1] != list(REQUIREMENTS_HEADER[:1])
            or generated[2:] != checked_in[2:]
        ):
            raise RuntimeError("requirements.txt is stale; regenerate it from uv.lock.")

        run(
            [
                sys.executable,
                "-m",
                "compileall",
                "-q",
                "voicetyping.py",
                "src",
                "tests",
                "scripts",
            ],
            env=environment,
        )
        run(
            ["uv", "run", "--locked", "python", "-m", "unittest", "discover", "-s", "tests"],
            env=environment,
        )
        run(
            ["uv", "run", "--locked", "python", "-m", "unittest", "discover", "-s", "tests/windows"],
            env=environment,
        )


def _clean_venv_python(venv: Path) -> Path:
    return venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def wheel_checks(args: argparse.Namespace) -> None:
    wheel = select_wheel(args.wheel)
    with tempfile.TemporaryDirectory(prefix="voicetyping-wheel-") as temporary:
        root = Path(temporary)
        venv = root / "venv"
        environment = isolated_environment(root / "environment")
        environment.setdefault("PIP_CACHE_DIR", str(root / "pip-cache"))
        run([sys.executable, "-m", "venv", str(venv)], env=environment)
        python = _clean_venv_python(venv)
        run(
            [str(python), "-m", "pip", "install", "--disable-pip-version-check", str(wheel)],
            env=environment,
        )
        version = run_capture(
            [str(venv / "bin/voicetyping"), "--version"], env=environment
        )
        package_version = args.version or read_package_version()
        if version.strip() != f"VoiceTyping {package_version}":
            raise RuntimeError(
                f"Installed command returned unexpected version: {version.strip()!r}"
            )
        toggle_command = venv / "bin/voicetyping-toggle"
        if not toggle_command.is_file() or not os.access(toggle_command, os.X_OK):
            raise RuntimeError("Wheel install did not create the voicetyping-toggle command.")
        toggle_help = run_capture([str(toggle_command), "--help"], env=environment)
        if toggle_help.strip() != "usage: voicetyping-toggle":
            raise RuntimeError("voicetyping-toggle did not return safe help output.")
        qualified_modules = tuple(f"voicetyping.{module}" for module in PACKAGE_MODULES)
        discovery_code = (
            "import importlib.util, sys; "
            f"modules={qualified_modules!r}; "
            "missing=[name for name in modules if importlib.util.find_spec(name) is None]; "
            "sys.exit('Missing package modules: ' + ', '.join(missing)) if missing else None"
        )
        run([str(python), "-c", discovery_code], env=environment)
        import_code = "import importlib; " + "; ".join(
            f"importlib.import_module('voicetyping.{module}')"
            for module in CLEAN_VENV_IMPORT_MODULES
        )
        run([str(python), "-c", import_code], env=environment)

        with zipfile.ZipFile(wheel) as archive:
            members = set(archive.namelist())
            missing = [
                f"voicetyping/{module}.py"
                for module in PACKAGE_MODULES
                if f"voicetyping/{module}.py" not in members
            ]
            if "voicetyping/__init__.py" not in members:
                missing.append("voicetyping/__init__.py")
            if missing:
                raise RuntimeError("Wheel is missing package modules: " + ", ".join(missing))

        exercise_installer_twice(root / "installer", wheel, package_version)


def run_capture(command: list[str], *, cwd: Path = ROOT, env: dict[str, str] | None = None) -> str:
    print("+", " ".join(str(part) for part in command), flush=True)
    return subprocess.run(
        command,
        cwd=cwd,
        env=env,
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def exercise_installer_twice(root: Path, wheel: Path, version: str) -> None:
    environment = isolated_environment(root)
    home = Path(environment["HOME"])
    shim = root / "bin"
    shim.mkdir(parents=True)
    systemctl = shim / "systemctl"
    systemctl.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    systemctl.chmod(0o755)
    config = home / ".config/voicetyping/config.json"
    config.parent.mkdir(parents=True)
    config.write_text('{"harness_sentinel": "preserve"}\n', encoding="utf-8")
    config.chmod(0o600)
    original_config = config.read_bytes()
    environment.update(
        {
            "VOICETYPING_WHEEL": str(wheel),
            "PATH": str(shim) + os.pathsep + environment.get("PATH", ""),
        }
    )
    environment.setdefault("PIP_CACHE_DIR", str(root.parent / "pip-cache"))
    installer = ROOT / "install.sh"
    for attempt in (1, 2):
        print(f"Installer idempotency pass {attempt}/2", flush=True)
        run(["bash", str(installer)], env=environment)
        current = home / ".local/bin/voicetyping/current"
        installed = current / ".venv/bin/voicetyping"
        output = run_capture([str(installed), "--version"], env=environment)
        if output.strip() != f"VoiceTyping {version}":
            raise RuntimeError(f"Isolated install returned unexpected version: {output.strip()!r}")

    install_root = home / ".local/bin/voicetyping"
    releases = sorted(
        path
        for path in (install_root / "releases").iterdir()
        if path.is_dir() and path.name.startswith(f"{version}-")
    )
    if len(releases) != 2:
        raise RuntimeError(f"Expected two rollback releases after rerun, found {len(releases)}.")
    if not (install_root / "current").is_symlink():
        raise RuntimeError("Installer did not leave the current release as an atomic symlink.")
    if config.read_bytes() != original_config or config.stat().st_mode & 0o777 != 0o600:
        raise RuntimeError("Installer changed the existing private configuration file.")
    for integration in (
        home / ".local/share/applications/voicetyping.desktop",
        home / ".config/autostart/voicetyping.desktop",
    ):
        if not integration.is_file():
            raise RuntimeError(f"Installer did not create desktop integration: {integration}")


def appimage_checks(args: argparse.Namespace) -> None:
    image = require_file(Path(args.image), "AppImage")
    expected = args.version or read_package_version()
    checksum = Path(args.checksum) if args.checksum else Path(str(image) + ".sha256")
    checksum = require_file(checksum, "AppImage checksum")
    run(["sha256sum", "--check", str(checksum)], cwd=image.parent)
    with tempfile.TemporaryDirectory(prefix="voicetyping-appimage-") as temporary:
        environment = isolated_environment(Path(temporary))
        check_command_version([str(image), "--version"], expected, env=environment)
        environment["APPIMAGE_EXTRACT_AND_RUN"] = "1"
        check_command_version([str(image), "--version"], expected, env=environment)
    check_static_appimage_runtime(image)


def check_static_appimage_runtime(image: Path) -> None:
    if shutil.which("readelf"):
        inspections = {}
        for mode in ("-d", "-l"):
            result = subprocess.run(
                ["readelf", mode, str(image)], capture_output=True, text=True
            )
            if result.returncode != 0:
                detail = result.stderr.strip() or "no diagnostic output"
                raise RuntimeError(f"readelf {mode} could not inspect AppImage: {detail}")
            inspections[mode] = result.stdout
        dynamic = inspections["-d"]
        if "(NEEDED)" in dynamic:
            raise RuntimeError("AppImage runtime has dynamic library dependencies.")
        if "Requesting program interpreter" in inspections["-l"]:
            raise RuntimeError("AppImage runtime requires a host ELF interpreter.")
    else:
        raise RuntimeError("readelf is required for AppImage runtime checks.")


def deb_checks(args: argparse.Namespace) -> None:
    package = require_file(Path(args.package), "Debian package")
    expected = args.version or read_package_version()
    version = run_capture(["dpkg-deb", "--field", str(package), "Version"]).strip()
    if version != f"{expected}-1":
        raise RuntimeError(
            f"Debian metadata version is {version!r}, expected {expected}-1."
        )
    architecture = run_capture(
        ["dpkg-deb", "--field", str(package), "Architecture"]
    ).strip()
    if architecture != "amd64":
        raise RuntimeError(
            f"Debian package architecture is {architecture!r}, expected 'amd64'."
        )
    contents = run_capture(["dpkg-deb", "--contents", str(package)])
    for module in PACKAGE_MODULES:
        if f"voicetyping/{module}.py" not in contents:
            raise RuntimeError(f"Debian package is missing voicetyping/{module}.py")
    if args.install:
        if os.geteuid() != 0:
            raise RuntimeError("--install requires root; run in a disposable Ubuntu 24.04 container.")
        run(["apt-get", "install", "--yes", str(package)])
        with tempfile.TemporaryDirectory(prefix="voicetyping-deb-") as temporary:
            environment = isolated_environment(Path(temporary))
            check_command_version(["voicetyping", "--version"], expected, env=environment)


def check_command_version(
    command: list[str], expected: str, *, env: dict[str, str] | None = None
) -> None:
    output = run_capture(command, env=env)
    if output.strip() != f"VoiceTyping {expected}":
        raise RuntimeError(f"Command returned unexpected version: {output.strip()!r}")


def read_package_version() -> str:
    source = ROOT / "src/voicetyping/__init__.py"
    tree = ast.parse(source.read_text(encoding="utf-8"), filename=str(source))
    versions = [
        node.value.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "__version__"
            for target in node.targets
        )
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    ]
    if len(versions) != 1 or re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", versions[0]) is None:
        raise RuntimeError("Could not read one semantic voicetyping.__version__ value.")
    return versions[0]


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    commands = result.add_subparsers(dest="command", required=True)
    commands.add_parser("source", help="Validate lock/export, compile, and run offline tests")
    wheel = commands.add_parser("wheel", help="Install and inspect a wheel in a clean environment")
    wheel.add_argument("--wheel", help="Wheel path; defaults to the sole dist/ wheel")
    wheel.add_argument(
        "--version", help="Expected application version; defaults to voicetyping.__version__"
    )
    appimage = commands.add_parser("appimage", help="Check AppImage checksum, launch, and ELF runtime")
    appimage.add_argument("image", help="AppImage path")
    appimage.add_argument("--checksum", help="Checksum file; defaults to IMAGE.sha256")
    appimage.add_argument("--version", help="Expected application version")
    deb = commands.add_parser("deb", help="Check Debian package metadata and contents")
    deb.add_argument("package", help=".deb package path")
    deb.add_argument("--version", help="Expected application version")
    deb.add_argument(
        "--install",
        action="store_true",
        help="Install with apt and check --version; requires root in a disposable Ubuntu image",
    )
    return result


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        {"source": source_checks, "wheel": wheel_checks, "appimage": appimage_checks, "deb": deb_checks}[
            args.command
        ](args)
    except (
        OSError,
        RuntimeError,
        SyntaxError,
        ValueError,
        zipfile.BadZipFile,
        subprocess.CalledProcessError,
    ) as error:
        print(f"release harness failed: {error}", file=sys.stderr)
        return 1
    print(f"release harness passed: {args.command}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
